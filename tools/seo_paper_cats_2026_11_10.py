def main():
    cat = json.load(open(CAT, encoding='utf-8'))
    done = 0
    for c in cat['categories']:
        slug = c['path'].rstrip('/').split('/')[-1]
        if not c['path'].startswith('/product-category/offset-ar/') or slug not in CATS:
            continue
        new = CATS[slug]
        seo = c['seo']
        old_title = seo['title']
        old_desc = slug and next((t.split('content="')[1].split('"')[0] for t in seo['tags'] if 'name="description"' in t), '')
        seo['title'] = new['title']
        tags = []
        for t in seo['tags']:
            if 'name="description"' in t or 'property="og:description"' in t:
                t = t.replace(f'content="{old_desc}"', f'content="{new["desc"]}"')
            if 'property="og:title"' in t:
                t = t.replace(f'content="{old_title}"', f'content="{new["title"]}"')
            tags.append(t)
        seo['tags'] = tags
        old_j = json.dumps(old_title, ensure_ascii=False)[1:-1]
        seo['ld'] = [ld.replace(f'"name":"{old_j}"', '"name":"' + json.dumps(new['title'], ensure_ascii=False)[1:-1] + '"') for ld in seo.get('ld', [])]
        c['description'] = new['body'] + WHY + HOW
        done += 1
        print(slug, '|', old_title, '->', new['title'], '| desc', len(new['desc']))
    if done != len(CATS):
        raise SystemExit(f'expected {len(CATS)} categories, changed {done}')
    if '--dry' not in sys.argv:
        json.dump(cat, open(CAT, 'w', encoding='utf-8'), ensure_ascii=False)
        print('written')


if __name__ == '__main__':
    main()
